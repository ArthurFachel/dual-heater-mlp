"""Width sweep: does capacity alone decide whether hard protection helps?

`docs/hard_vs_soft_results.md` reports that hard protection beats soft where
capacity is loose and loses where it is tight. That reading is *suggestive but
not isolated*: across those five targets width, boundary count, classes per
task and examples per class all varied together. Split-CIFAR-100 flips the
sign relative to Split-CIFAR-10 on the same backbone, but it also doubles the
boundaries, quintuples the classes per task and cuts the data tenfold.

This suite varies exactly one thing. Dataset, task schedule, epochs, learning
rate, capacity budget, protection strength, seeds and replay indices are held
fixed; only ``hidden_dims`` moves, along a 2:1 ladder. If the capacity reading
is right, the Hard-minus-Soft difference should grow with width. If it does
not, the reading in the results document is wrong and must be retracted.

Primary test, declared before execution
---------------------------------------
For each seed ``s`` we have the paired difference ``d_s(w) = hard - soft`` at
each width ``w``. We fit one slope per seed,

    d_s(w) ~ a_s + b_s * log2(w)

and test ``H0: b = 0`` against ``H1: b > 0`` over the ten ``b_s``. This is a
single primary test on ten paired observations, so no multiplicity correction
is needed for it; per-width contrasts are secondary and Holm-corrected within
their own family.

Using the slope per seed rather than the per-width means is what makes the
test paired: every seed contributes its own trend, and seed-level variation in
absolute accuracy cancels out.

Replication control
-------------------
The ``(1024, 512)`` rung is the width already run by `experiments.hard_vs_soft`
on the same ten seeds. It is re-run here rather than imported, so every rung
shares one source fingerprint. Its agreement with the existing aggregate is
checked by `analyze_capacity_sweep.py` and is an independent replication of the
only Holm-surviving primary contrast in that suite -- the same aggregate this
project has never replicated for any other result.
"""

from __future__ import annotations

import argparse
import json
import random
from dataclasses import asdict, dataclass, replace
from pathlib import Path
from typing import Any

from experiments.artifacts import write_json_atomic
from experiments.confirmatory_split_mnist import CONFIRMATORY_SEEDS
from experiments.confirmatory_statistics import PRIMARY_ENDPOINT
from experiments.dualheat_pairs import MethodPair, _holm_adjust, summarize_pair_results
from experiments.hard_vs_soft import HARD, HARD_REPLAY, SOFT, SOFT_REPLAY
from experiments.provenance import relative_path
from experiments.split_mnist import (
    SplitMNISTConfig,
    config_payload,
    replay_selection_is_method_independent,
    run_split_mnist_multi_seed,
)
from experiments.visual_generalization import (
    generalization_configs,
    load_split_cifar10,
    load_split_cifar100,
)

#: Same contrasts as the hard-versus-soft suite, so the two are directly
#: comparable at the shared width. The primary contrast comes first.
METHOD_PAIRS = (
    MethodPair("Hard vs Soft", SOFT, HARD),
    MethodPair("Hard vs Soft (replay)", SOFT_REPLAY, HARD_REPLAY),
    MethodPair("Hard vs Replay", "replay", HARD_REPLAY),
    MethodPair("Hard vs Vanilla", "vanilla", HARD),
)

PAIRED_METHODS = tuple(
    dict.fromkeys(
        method for pair in METHOD_PAIRS for method in (pair.reference, pair.candidate)
    )
)

#: A 2:1 ladder spanning 16x. The third rung is the width already run by the
#: hard-versus-soft suite and serves as the replication control.
WIDTHS: tuple[tuple[int, ...], ...] = (
    (128, 64),
    (256, 128),
    (512, 256),
    (1024, 512),
    (2048, 1024),
)

REPLICATION_WIDTH = (1024, 512)

DATASETS = ("split_cifar10", "split_cifar100")

#: The seeds the hard-versus-soft suite drew and recorded before training.
#: Reused deliberately: the shared rung is only a replication control if the
#: seeds match. Regenerated by the same deterministic draw rather than pasted.
SWEEP_SEEDS = random.Random(20_260_923).sample(range(2**31), 10)


@dataclass(frozen=True)
class SweepTarget:
    dataset: str
    width: tuple[int, ...]

    @property
    def name(self) -> str:
        return f"{self.dataset}_w{'x'.join(str(w) for w in self.width)}"


def sweep_config(
    dataset: str, width: tuple[int, ...], device: str = "cpu"
) -> SplitMNISTConfig:
    """The hard-versus-soft config for this dataset, with only the width moved."""
    if dataset not in DATASETS:
        raise ValueError(
            f"dataset não suportado: {dataset}; disponíveis: {', '.join(DATASETS)}"
        )
    if not width or any(w < 1 for w in width):
        raise ValueError("width deve conter dimensões positivas")
    base = generalization_configs(device)[dataset]
    if base.backbone != "mlp":
        raise ValueError(f"o sweep de largura requer MLP, não {base.backbone}")
    return replace(
        base,
        hidden_dims=tuple(width),
        methods=PAIRED_METHODS,
        slow_strength=30.0,
        plasticity_budget=0.25,
        optimizer_state_policy="follow_update",
    )


def _validate_seeds(seeds: list[int]) -> None:
    if not seeds or any(type(seed) is not int or seed < 0 for seed in seeds):
        raise ValueError("seeds deve conter inteiros não negativos")
    if len(set(seeds)) != len(seeds):
        raise ValueError("seeds não pode conter duplicatas")
    reserved = set(seeds).intersection(CONFIRMATORY_SEEDS)
    if reserved:
        raise ValueError(
            f"seeds reservadas à confirmação congelada não podem entrar: {sorted(reserved)}"
        )


def sweep_protocol(
    config: SplitMNISTConfig,
    seeds: list[int],
    *,
    dataset: str,
    width: tuple[int, ...],
) -> dict[str, Any]:
    config.validate()
    _validate_seeds(seeds)
    if config.methods != PAIRED_METHODS:
        raise ValueError("a suíte requer exatamente os métodos declarados")
    if config.optimizer_state_policy != "follow_update":
        raise ValueError("a suíte requer optimizer_state_policy=follow_update")
    if tuple(config.hidden_dims) != tuple(width):
        raise ValueError("config.hidden_dims diverge da largura declarada")
    return {
        "schema_version": 1,
        "status": "exploratory_frozen_before_execution",
        "question": (
            "The hard-versus-soft suite read its result as capacity pressure, "
            "but width, boundary count and data volume varied together there. "
            "With only the width moving, does the Hard-minus-Soft difference "
            "grow with capacity?"
        ),
        "dataset": dataset,
        "backbone": "mlp",
        "width": list(width),
        "width_ladder": [list(w) for w in WIDTHS],
        "held_fixed": [
            "dataset and class order",
            "tasks, classes per task and examples per class",
            "epochs per task, batch size, learning rate, weight decay",
            "capacity budget (0.25) and protection strength (beta = 30)",
            "seeds, paired initialization, batches and replay indices",
        ],
        "varied": "hidden_dims only, along a 2:1 ladder from (128, 64) to (2048, 1024)",
        "pairs": [asdict(pair) for pair in METHOD_PAIRS],
        "primary_contrast": METHOD_PAIRS[0].label,
        "seeds": seeds,
        "config": json.loads(json.dumps(config_payload(config))),
        "primary_endpoint": PRIMARY_ENDPOINT,
        "difference_direction": "candidate_minus_reference",
        "primary_test": {
            "statistic": "per-seed OLS slope of (hard - soft) on log2(first hidden width)",
            "null": "b = 0 (width does not modulate the regime difference)",
            "alternative": "b > 0 (hard gains on soft as capacity grows)",
            "test": "one-sided paired t over the 10 per-seed slopes, plus exact sign test",
            "multiplicity": "single primary test; per-width contrasts are secondary",
        },
        "declared_expectations": [
            (
                "The capacity reading of docs/hard_vs_soft_results.md predicts a "
                "positive slope: hard should overtake soft as width grows."
            ),
            (
                "A null slope falsifies that reading and the results document "
                "must be corrected to drop the capacity explanation."
            ),
            (
                "A negative slope would mean hard does worse with more capacity, "
                "contradicting both the reading and the plasticity-floor argument."
            ),
        ],
        "replication_control": {
            "width": list(REPLICATION_WIDTH),
            "compare_against": f"results/hard_vs_soft/{dataset}_mlp/pair_report.json",
            "rationale": (
                "Same seeds and same config as the hard-versus-soft suite, so "
                "this rung independently replicates that aggregate."
            ),
        },
        "limitations": [
            "Fixed defaults, not individually tuned baselines; no universal benefit claim.",
            "No task ID at inference; known task boundaries at consolidation.",
            "Exploratory: this suite is not a preregistered confirmation.",
            "Width is varied at a fixed 2:1 layer ratio and fixed depth.",
        ],
    }


def run_target(
    *,
    dataset: str,
    width: tuple[int, ...],
    seeds: list[int],
    data_dir: str | Path,
    output_dir: str | Path,
    device: str = "cpu",
    download: bool = True,
    verbose: bool = True,
    resume: bool = True,
) -> dict[str, Any]:
    config = sweep_config(dataset, width, device)
    if not replay_selection_is_method_independent(config.replay_selection):
        raise ValueError(
            "a suíte requer replay_selection='first'; seleção adaptativa "
            "pertence ao tratamento experimental"
        )
    loaders = {
        "split_cifar10": load_split_cifar10,
        "split_cifar100": load_split_cifar100,
    }
    protocol = sweep_protocol(config, seeds, dataset=dataset, width=width)
    output = Path(output_dir)
    lock = output / "capacity_sweep_protocol.json"
    if lock.exists():
        if not resume or json.loads(lock.read_text(encoding="utf-8")) != protocol:
            raise ValueError(
                "protocolo diferente ou resume desativado; use outro output_dir"
            )
    elif output.exists() and any(output.iterdir()):
        raise ValueError("output_dir deve estar vazio para iniciar a suíte")
    else:
        write_json_atomic(lock, protocol)
    run_split_mnist_multi_seed(
        config,
        seeds=seeds,
        data_dir=data_dir,
        output_dir=output,
        download=download,
        verbose=verbose,
        paired_references=(),
        task_loader=loaders[dataset],
        resume=resume,
    )
    report = summarize_pair_results(output, output_dir=output, pairs=METHOD_PAIRS)
    if len(seeds) >= 2:
        adjusted = _holm_adjust(
            [
                pair["metrics"][PRIMARY_ENDPOINT]["student_t"]["two_sided_p"]
                for pair in report["pairs"]
            ]
        )
        for pair, value in zip(report["pairs"], adjusted, strict=True):
            pair["metrics"][PRIMARY_ENDPOINT]["holm_adjusted_p"] = value
        report["multiplicity"] = (
            "Holm over the four accuracy contrasts at this width; the sweep's "
            "primary test is the slope across widths, not these contrasts"
        )
        write_json_atomic(output / "pair_report.json", report)
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--datasets", nargs="+", choices=DATASETS, default=list(DATASETS))
    parser.add_argument(
        "--widths",
        nargs="+",
        help="larguras como '256x128'; default é a escada completa",
    )
    parser.add_argument("--seeds", type=int, nargs="+")
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument(
        "--output-dir", type=Path, default=Path("results/capacity_sweep")
    )
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--no-download", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    widths = WIDTHS
    if args.widths:
        widths = tuple(
            tuple(int(part) for part in spec.split("x")) for spec in args.widths
        )
    seeds = args.seeds if args.seeds is not None else list(SWEEP_SEEDS)

    targets = [
        SweepTarget(dataset, width)
        for dataset in dict.fromkeys(args.datasets)
        for width in widths
    ]
    if args.dry_run:
        payload = {
            target.name: sweep_protocol(
                sweep_config(target.dataset, target.width, args.device),
                seeds,
                dataset=target.dataset,
                width=target.width,
            )
            for target in targets
        }
        print(json.dumps(payload, indent=2, sort_keys=True))
        return 0

    for target in targets:
        output = args.output_dir / target.name
        run_target(
            dataset=target.dataset,
            width=target.width,
            seeds=seeds,
            data_dir=args.data_dir,
            output_dir=output,
            device=args.device,
            download=not args.no_download,
        )
        print(f"Relatório: {relative_path(output / 'pair_report.md', base=Path.cwd())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
